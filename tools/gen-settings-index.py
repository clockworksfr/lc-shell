#!/usr/bin/env python3
"""Builds settings/Index.qml: every setting label (Field `label:` keys) and
section title of the settings pages, for the settings search.
Run after adding or renaming a setting: python3 tools/gen-settings-index.py
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = ["appearance", "bar", "screens", "dashboard", "wallpaper", "notifications", "modes", "network", "bluetooth", "sound", "clipboard", "screenshot", "lock", "weather", "system", "shortcuts"]
KEY = re.compile(r'\b(label|title|hint): I18n\.tr\("([^"]+)"')

entries = []
for page in PAGES:
    path = os.path.join(ROOT, "settings", f"{page[0].upper()}{page[1:]}Page.qml")
    if not os.path.exists(path):
        continue
    last = None
    for kind, key in KEY.findall(open(path, encoding="utf-8").read()):
        if kind == "hint":
            if last:
                last["hint"] = key
            continue
        last = {"page": page, "key": key, "hint": ""}
        entries.append(last)

lines = [f'        {{ page: "{e["page"]}", key: "{e["key"]}", hint: "{e["hint"]}" }}' for e in entries]
out = """pragma Singleton

import QtQuick
import Quickshell

// Settings searchable from the settings window: { page, key (label i18n
// key), hint (i18n key or "") }. Generated by tools/gen-settings-index.py.
Singleton {
    readonly property var entries: [
""" + ",\n".join(lines) + """
    ]
}
"""
open(os.path.join(ROOT, "settings", "Index.qml"), "w", encoding="utf-8").write(out)
print(len(entries), "entries")
